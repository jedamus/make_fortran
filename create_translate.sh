#files2=$(find src/ -maxdepth 2 -type f \( -name '*.F' -o -name '*.FOR' -o -name '*.FTN' -o -name '*.FPP' -o -name '*.F77'\
#  -o -name '*.F90' -o -name '*.F95' -o -name '*.F03' -o -name '*.F08' \))

