usage() {
  echo "usage: $0 translate <project> <lib1> <lib2>"
  exit 0
}

create() {
  local translate=$1
  shift
  local project=$1
  shift
  local files="$*"

  tmpfile=$(mktemp)
  is_first=1
  for file in $files; do
    grep "_(" $file > $tmpfile
    if [ -s $tmpfile ]; then
      echo "analyzing $file"
      if [ $is_first = 1 ]; then
        echo -n "${translate}.pl " >> ${translate}.sh
	is_first=0
      fi
      echo -n "--file $file " >> ${translate}.sh
    fi
  done
  if [ $is_first != 1 ]; then
    echo "--project=$project --version=\$(cat version.txt)" >> ${translate}.sh
  fi
  rm $tmpfile
}

if [ -z $1 ]; then
  usage
fi

program=$(basename $0)

translate=$1
shift
srclib=$1
shift
project=$1
shift
libs="$*"

DATETIME=$(date +"%A, %d. %B %Y %H:%M")

names="-name '*.F' -o -name '*.FOR' -o -name '*.FTN' -o -name '*.FPP' -o -name '*.F77'"\
" -o -name '*.F90' -o -name '*.F95' -o -name '*.F03' -o -name '*.F08'"
