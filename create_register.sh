# set -x

if [ -z $1 ]; then
  echo "usage: $0 <SRCDIR> <SRCLIB> <domain> <gettext.h> <my_register> <libname1> <libname2> ..."
  exit 1
fi

program=$(basename $0)

srcdir=$1
shift
srclib=$1
shift
domain=$1
shift
gettext_h=$1
shift
my_register=$1
shift
libs="$*"

DATETIME=$(date +"%A, %d. %B %Y %H:%M")
GETTEXT_H=$(echo $gettext_h | sed -e 's/\./_/g' | tr [:lower:] [:upper:])

filename1=$srcdir/${my_register}.F90

echo "creating $filename1."
cat << EOF > $filename1
! erzeugt Dienstag, 12. Mai 2026 11:12 (C) 2026 von Leander Jedamus
! modifiziert $DATETIME von Leander Jedamus

! auto generated by $program. Do not edit!

! #define DOMAIN "$domain"

#include "$gettext_h"
       
MODULE $my_register

  USE mod_gettext
  USE mod_getlocaledir
EOF

for lib in $libs; do
  echo "  USE ${my_register}_lib$lib" >> $filename1
done

cat << EOF >> $filename1
  IMPLICIT NONE
  PRIVATE

  PUBLIC :: register

  CONTAINS

  SUBROUTINE register()
    IMPLICIT NONE
    INTEGER :: i, argc, length
    INTEGER, PARAMETER :: maxlen = 4096
    CHARACTER(LEN=:), ALLOCATABLE :: arg
    CHARACTER(len=:), ALLOCATABLE :: pfad

    CALL setlocale()

    argc = COMMAND_ARGUMENT_COUNT()
    argc = 0
    CALL GET_COMMAND_ARGUMENT(argc, length=length)
    ALLOCATE(CHARACTER(length) :: arg)
    CALL GET_COMMAND_ARGUMENT(argc, VALUE=arg)
    pfad = getlocaledir(arg)

    CALL bindtextdomain(DOMAIN, pfad)
    CALL textdomain(DOMAIN)

EOF

for lib in $libs; do
  echo "    CALL register_lib_$lib(pfad)" >> $filename1
done

cat << EOF >> $filename1
  END SUBROUTINE register

END MODULE my_register
       
! vim:ai sw=4 expandtab

EOF

for lib in $libs; do
  filename2=$srclib/$lib/${my_register}_lib$lib.F90
  echo "creating $filename2."

cat << EOF > $filename2
! erzeugt Mittwoch, 13. Mai 2026 09:41 (C) 2026 von Leander Jedamus
! modifiziert $DATETIME von Leander Jedamus

! auto generated by $program. Do not edit!

! #define DOMAIN "${domain}_lib$lib"

#define DOMAIN_SUFFIX "lib$lib"
#include "$gettext_h"
       
MODULE ${my_register}_lib$lib
  USE mod_gettext

  IMPLICIT NONE
  PRIVATE

  PUBLIC :: register_lib_$lib

  CONTAINS

  SUBROUTINE register_lib_$lib(pfad)
    IMPLICIT NONE
    CHARACTER(len=*), INTENT(IN) :: pfad

    CALL bindtextdomain(DOMAIN, pfad)
  END SUBROUTINE register_lib_$lib

END MODULE ${my_register}_lib$lib
       
! vim:ai sw=4 expandtab

EOF
done

filename3=$srcdir/$gettext_h
echo "creating $filename3."
cat << EOF > $filename3
/* -*- C -*- */
/* $gettext_h */
/* erzeugt Dienstag, 21. Juli 2026 11:04 (C) 2026 von Leander Jedamus */
/* modifiziert $DATETIME von Leander Jedamus */

/* auto generated by $program. Do not edit! */

#ifndef $GETTEXT_H
#define $GETTEXT_H 1

#define _DOMAIN "${domain}"

#ifdef __GFORTRAN__
#  define _JOIN //
#else
#  define _JOIN
#endif

#ifdef DOMAIN_SUFFIX
#  define DOMAIN _DOMAIN _JOIN "_" _JOIN DOMAIN_SUFFIX
#else
#  define DOMAIN _DOMAIN
#endif

#ifdef IS_LIB
#  define _(msgid) dgettext (DOMAIN, msgid)
#else
#  define _(msgid) gettext (msgid)
#endif
       
#endif /* $GETTEXT_H */

/* vim:set cindent ai sw=2 */

EOF

