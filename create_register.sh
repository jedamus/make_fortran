# set -x

if [ -z $1 ]; then
  echo "usage: $0 <SRCDIR> <domain> <my_register> <libname1> <libname2> ..."
  exit 1
fi

program=$(basename $0)

srcdir=$1
shift
domain=$1
shift
my_register=$1
shift
libs="$*"

DATETIME=$(date +"%A, %d. %B %Y %H:%M")

filename1="$srcdir/${my_register}.F90"

cat << EOF > $filename1
! erzeugt Dienstag, 12. Mai 2026 11:12 (C) 2026 von Leander Jedamus
! modifiziert $DATETIME von Leander Jedamus

! auto generated by $program. Do not edit!

#define DOMAIN "$domain"
       
MODULE $my_register

  USE mod_gettext
  USE mod_getlocaledir
EOF

for i in $libs; do
  echo "  USE ${my_register}_lib$i" >> $filename1
done

cat << EOF >> $filename1
  IMPLICIT NONE
  PRIVATE

  PUBLIC :: register

  CONTAINS

  SUBROUTINE register()
    IMPLICIT NONE
    INTEGER :: i, argc, length
    INTEGER, PARAMETER :: maxlen = 4096
    CHARACTER(LEN=:), ALLOCATABLE :: arg
    CHARACTER(len=:), ALLOCATABLE :: pfad

    CALL setlocale()

    argc = COMMAND_ARGUMENT_COUNT()
    argc = 0
    CALL GET_COMMAND_ARGUMENT(argc, length=length)
    ALLOCATE(CHARACTER(length) :: arg)
    CALL GET_COMMAND_ARGUMENT(argc, VALUE=arg)
    pfad = getlocaledir(arg)

    CALL bindtextdomain(DOMAIN, pfad)
    CALL textdomain(DOMAIN)

EOF

for i in $libs; do
  echo "    CALL register_lib_$i(pfad)" >> $filename1
done

cat << EOF >> $filename1
  END SUBROUTINE register

END MODULE my_register
       
! vim:ai sw=4 expandtab

EOF

for i in $libs; do
  filename2=$srcdir/lib/$i/${my_register}_lib$i.F90

cat << EOF > $filename2
! erzeugt Mittwoch, 13. Mai 2026 09:41 (C) 2026 von Leander Jedamus
! modifiziert $DATETIME von Leander Jedamus

! auto generated by $program. Do not edit!

#define DOMAIN "${domain}_lib$i"
       
MODULE ${my_register}_lib$i
  USE mod_gettext

  IMPLICIT NONE
  PRIVATE

  PUBLIC :: register_lib_$i

  CONTAINS

  SUBROUTINE register_lib_$i(pfad)
    IMPLICIT NONE
    CHARACTER(len=*), INTENT(IN) :: pfad

    CALL bindtextdomain(DOMAIN, pfad)
  END SUBROUTINE register_lib_$i

END MODULE ${my_register}_lib$i
       
! vim:ai sw=4 expandtab

EOF
done

